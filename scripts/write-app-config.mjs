#!/usr/bin/env node
// Writes the app's local-development config (both files git-ignored, shapes in config.example.ts):
//   apps/vega/src/platform/config.generated.ts          API address, backend, PlayerLab (no secrets)
//   apps/vega/src/platform/devCredentials.generated.ts  seeded TV user; config.ts requires it only
//                                                       under __DEV__, so release bundles omit it
// Usage:
//   node scripts/write-app-config.mjs                     # local Inox stack (default)
//   node scripts/write-app-config.mjs --backend mock      # tools/mock-inox on :18090
//   node scripts/write-app-config.mjs --player-lab <url> [--lab-level -1] [--lab-hls '{"maxBufferLength":30}']
// The API is reached as localhost because the VVD reverse-forwards the port (scripts/vvd-forward.sh).
// Dev builds prefill the TV user so sign-in is operable with select alone.
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] !== undefined ? args[i + 1] : fallback;
};

const backend = opt('--backend', 'stack');
let apiBase;
let tv;
if (backend === 'mock') {
  // tools/mock-inox: same seeded e-mail as the stack; mock-only password (guards nothing).
  apiBase = process.env.APP_API_BASE ?? 'http://localhost:18090/api/v1';
  tv = { email: 'tv@fireos-inox.test', password: process.env.MOCK_PASSWORD ?? 'mock-only-password' };
} else if (backend === 'stack') {
  const credPath = join(root, '.devstack', 'seed-credentials.json');
  apiBase = process.env.APP_API_BASE ?? 'http://localhost:18080/api/v1';
  tv = existsSync(credPath) ? JSON.parse(readFileSync(credPath, 'utf8')).tv : null;
} else {
  console.error(`unknown --backend ${backend} (stack | mock)`);
  process.exit(1);
}

const labUrl = opt('--player-lab', '');
const playerLab = labUrl ? { url: labUrl, level: Number(opt('--lab-level', '-1')), hls: JSON.parse(opt('--lab-hls', '{}')), suite: opt('--lab-suite', 'basic') } : null;

const header = '// Generated by scripts/write-app-config.mjs — do not commit.\n';
const config = `${header}export const generatedConfig = {
  backend: ${JSON.stringify(backend)},
  apiBaseUrl: ${JSON.stringify(apiBase)},
  wsBaseUrl: ${JSON.stringify(apiBase.replace(/^http/, 'ws'))},
  playerLab: ${JSON.stringify(playerLab)} as null | {url: string; level: number; hls: Record<string, unknown>; suite: string},
};
`;
// Never import this file statically: config.ts requires it inside a __DEV__ branch so Metro drops it
// from release bundles (a static import bundles the password even when unused).
const devCredentials = `${header}export const devCredentials = {
  email: ${JSON.stringify(tv?.email ?? '')},
  password: ${JSON.stringify(tv?.password ?? '')},
};
`;
const dir = join(root, 'apps', 'vega', 'src', 'platform');
const write = (name, text) => {
  const target = join(dir, name);
  writeFileSync(target, text, { mode: 0o600 });
  chmodSync(target, 0o600); // mode only applies when the file is created
  return target;
};
const target = write('config.generated.ts', config);
write('devCredentials.generated.ts', devCredentials);
console.log(`wrote ${target} + devCredentials.generated.ts (backend ${backend}, api ${apiBase}, dev user ${tv?.email ?? 'none'}${playerLab ? `, player lab ${labUrl}` : ''})`);
