#!/usr/bin/env node
// Writes apps/vega/src/platform/config.generated.ts (git-ignored) for local development.
// The API is reached as localhost because scripts/vvd-forward.sh reverse-forwards port 18080 into
// the VVD. Dev builds prefill the seeded TV user so sign-in is operable with select alone.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const credPath = join(root, '.devstack', 'seed-credentials.json');
const tv = existsSync(credPath) ? JSON.parse(readFileSync(credPath, 'utf8')).tv : null;
const apiBase = process.env.APP_API_BASE ?? 'http://localhost:18080/api/v1';

const out = `// Generated by scripts/write-app-config.mjs — do not commit.
export const generatedConfig = {
  apiBaseUrl: ${JSON.stringify(apiBase)},
  wsBaseUrl: ${JSON.stringify(apiBase.replace(/^http/, 'ws'))},
  devEmail: ${JSON.stringify(tv?.email ?? '')},
  devPassword: ${JSON.stringify(tv?.password ?? '')},
};
`;
const target = join(root, 'apps', 'vega', 'src', 'platform', 'config.generated.ts');
writeFileSync(target, out, { mode: 0o600 });
console.log(`wrote ${target} (api ${apiBase}, dev user ${tv?.email ?? 'none'})`);
